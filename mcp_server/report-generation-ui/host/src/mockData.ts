塔器方面，甲醇回收塔、催化蒸馏塔A、催化蒸馏塔B采用并联扩能；异戊烯精制塔采用串联扩能。

反应器方面，醚化反应器实施扩容或本体改造；醚解反应器、异构化反应器采用并联扩能；新醚化反应器利旧现有设备。

